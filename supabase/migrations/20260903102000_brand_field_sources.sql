-- ============================================================================
-- 5. Storage bucket brand-logos
-- ============================================================================
-- Private bucket, path shape org/<organization_id>/<file>. Any active member
-- (owner or clinician) may read/write — lock enforcement on who may replace
-- the practice charter's logo is a later lot, same as field_sources above.

insert into storage.buckets (id, name, public)
values ('brand-logos', 'brand-logos', false)
on conflict (id) do nothing;

-- storage.foldername(name)[2] is attacker-controlled text (the object path a
-- client uploads to), so casting it to uuid can raise. A cast failure inside
-- an RLS predicate must read as "no access", not as a 500 — this wraps the
-- cast so an exception becomes false, never an error.
create or replace function public.can_access_org_logo_path(p_name text)
returns boolean
language plpgsql
stable
security definer
set search_path = ''
as $$
declare
  v_folders text[];
  v_org_id  uuid;
begin
  v_folders := storage.foldername(p_name);

  if v_folders is null or array_length(v_folders, 1) < 2 or v_folders[1] <> 'org' then
    return false;
  end if;

  begin
    v_org_id := v_folders[2]::uuid;
  exception when others then
    return false;
  end;

  return public.is_org_member(v_org_id);
end;
$$;

comment on function public.can_access_org_logo_path(text) is
  'True iff p_name (a storage.objects.name) is shaped org/<uuid>/... and the calling user is an active member of that organization. A malformed second path segment (not a uuid) is caught and returns false rather than raising.';

revoke execute on function public.can_access_org_logo_path(text) from public, anon, authenticated;
grant  execute on function public.can_access_org_logo_path(text) to authenticated;

create policy "brand_logos_select_org"
  on storage.objects for select
  to authenticated
  using (bucket_id = 'brand-logos' and public.can_access_org_logo_path(name));

create policy "brand_logos_insert_org"
  on storage.objects for insert
  to authenticated
  with check (bucket_id = 'brand-logos' and public.can_access_org_logo_path(name));

create policy "brand_logos_update_org"
  on storage.objects for update
  to authenticated
  using (bucket_id = 'brand-logos' and public.can_access_org_logo_path(name))
  with check (bucket_id = 'brand-logos' and public.can_access_org_logo_path(name));

create policy "brand_logos_delete_org"
  on storage.objects for delete
  to authenticated
  using (bucket_id = 'brand-logos' and public.can_access_org_logo_path(name));
