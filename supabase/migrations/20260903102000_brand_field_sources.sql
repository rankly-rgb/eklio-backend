-- ============================================================================
-- Eklio — tenancy layer, lot 1: per-field brand source and logo import
-- ============================================================================
-- The provenance of a brand's fields — generated / imported / derived /
-- inherited — because the practice offer must reproduce an existing visual
-- identity exactly, and a clinician must inherit locked fields from the
-- practice charter. The map lives on site_specs, the same row as the fields
-- it describes (see the Step 0 inventory: site_specs is SPEC, not brand_kits).
-- ============================================================================


-- ============================================================================
-- 1. brand_kits.origin
-- ============================================================================

alter table public.brand_kits
  add column origin text not null default 'generated';

alter table public.brand_kits
  add constraint brand_kits_origin_check check (origin in ('generated', 'imported', 'mixed'));

comment on column public.brand_kits.origin is
  'Whether this kit''s brand was generated by Eklio, imported from an existing practice identity, or mixed (imported, then partly regenerated). Deliberately coarse — the field-by-field detail lives in site_specs.field_sources.';


-- ============================================================================
-- 2. site_specs.field_sources
-- ============================================================================
-- Allowed keys are derived from SPEC's actual editable columns: the six
-- colour roles and the typography pair map 1:1 to real site_specs columns.
-- `logo` is ONE conceptual key covering all four logo asset columns added
-- below — field_sources describes the provenance of a field the editor shows
-- the practitioner, not of an individual storage path.
--
-- ⚠ `tone` is NOT included. site_specs has no tone column — nothing on this
-- table is a "tone" field to source-track (project_briefs has a tone_card_id,
-- but that is brief input, not an editable SPEC field). Flagged in the
-- checkpoint report as a deviation from the literal brief, which named `tone`
-- among the allowed keys; omitted here because the instruction's own primary
-- rule is to derive the list from SPEC's actual columns, and there is no such
-- column.

alter table public.site_specs
  add column field_sources jsonb not null default '{}'::jsonb;

create or replace function public.validate_field_sources(p jsonb)
returns boolean
language sql
immutable
strict
set search_path = ''
as $$
  select coalesce(
    jsonb_typeof(p) = 'object'
    and not exists (
      select 1
        from jsonb_each_text(p) as kv(key, value)
       where kv.key not in (
               'primary_hex', 'secondary_hex', 'accent_hex',
               'light_neutral_hex', 'dark_neutral_hex', 'paper_hex',
               'heading_font', 'body_font', 'logo'
             )
          or kv.value not in ('generated', 'imported', 'derived', 'inherited')
    ),
  false)
$$;

comment on function public.validate_field_sources(jsonb) is
  'True iff every key of p is one of the nine tracked SPEC fields (six colour roles, heading_font, body_font, logo) and every value is one of generated/imported/derived/inherited. An empty object passes (no field has a recorded source yet). STRICT, so NULL input returns NULL — safe here only because site_specs.field_sources is NOT NULL, so the CHECK below never sees a NULL argument.';

-- Wired into a CHECK constraint, evaluated with the writing role's own
-- privileges (site_specs UPDATE is authenticated-only, RLS + column grants —
-- see 20260830060048_site_spec.sql). Unlike the repo's other 17 CHECK-wired
-- validators (deliberately left on Postgres's PUBLIC-EXECUTE default, per
-- 20260902090000_revoke_internal_function_surface.sql), this one is revoked
-- from anon explicitly: nothing about this function needs anon to reach it —
-- anon can never trigger this CHECK, since anon cannot write site_specs at
-- all — and closing it now is one fewer function for a future audit of the
-- other 17 to reconsider.
revoke execute on function public.validate_field_sources(jsonb) from public, anon;
grant  execute on function public.validate_field_sources(jsonb) to authenticated;

alter table public.site_specs
  add constraint site_specs_field_sources_check check (public.validate_field_sources(field_sources));

comment on column public.site_specs.field_sources is
  'Per-field provenance: key -> generated/imported/derived/inherited, for the six colour roles, heading_font, body_font, and logo. Read by the practice UI to show "why does this field look like this" and, later, to lock inherited fields. NOT enforced here — a client may still update a field marked inherited; rejecting that write is a later lot.';


